"""
\n - New Line
\t - Tab Space
\\ - Backslash
\" - Double Quote
\' - Single Quote

"""
print("Hello\nWorld")  # New Line
print("Hello\tWorld")  # Tab Space
print("Ojas\\Jaiswal")  # Backslash
print("My name is \"Ojas\" Jaiswal")  # Double Quote
print("My name is \'Ojas\' Jaiswal")  # Single Quote

